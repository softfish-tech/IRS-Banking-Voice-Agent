"""Public, provider-independent async LLM transport contract."""

from collections.abc import Mapping
from typing import Any, Protocol, TypeVar

from pydantic import BaseModel, ConfigDict, Field


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class LLMMessage(_Model):
    role: str = Field(pattern="^(system|user|assistant)$")
    content: str = Field(min_length=1, max_length=20_000)


class LLMRequest(_Model):
    """Transport input. Callers must not put secrets in messages or metadata."""

    model: str = Field(min_length=1, max_length=200)
    messages: tuple[LLMMessage, ...] = Field(min_length=1, max_length=32)
    max_output_tokens: int = Field(default=512, ge=1, le=4_096)
    temperature: float = Field(default=0, ge=0, le=2)
    # Generated by the calling module for one logical model operation. It must
    # be opaque and must never contain user text, credentials, or account data.
    idempotency_key: str | None = Field(default=None, min_length=1, max_length=128)


class LLMResult(_Model):
    request_id: str
    status: str = Field(pattern="^(ok|error)$")
    data: Mapping[str, Any] | None = None
    error_code: str | None = None
    attempts: int = Field(default=0, ge=0)
    prompt_tokens: int | None = Field(default=None, ge=0)
    completion_tokens: int | None = Field(default=None, ge=0)
    total_tokens: int | None = Field(default=None, ge=0)


ResponseModel = TypeVar("ResponseModel", bound=BaseModel)


class LLMClient(Protocol):
    async def generate(self, request: LLMRequest, response_model: type[ResponseModel]) -> LLMResult:
        """Return validated structured data or a sanitized transport error."""
